"""The fragment layouts against AMD's own tool.

`layouts.FRAGMENT_BITS` says where each element of a matrix operand lives.
That is a claim about hardware of exactly the kind this package keeps getting
wrong, and it is not one a reader can check: the layouts are irregular enough
that two instructions of the same shape and the same block count place their
accumulators differently.

AMD publishes them as a calculator rather than a table, so the check runs
against a vendored extract of what that tool says --- generated by
`tools/amd_matrix_layouts.py`, in the same shape and for the same reason as
the LLVM table behind `test_amd_catalog.py`.

The interesting property is not that the numbers round-trip.  It is that
`replication` comes out the same from two independent sources: from LLVM's
operand widths, through the invariant in `MatrixOp`, and from the calculator's
element positions.  Nothing forces those to agree.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from tensorforge.backend.instructions.compute.primitives.amd import (
    catalog, layouts)

LAYOUTS = Path(__file__).parent / "data" / "amd_matrix_layouts.json"


def _table():
    return json.loads(LAYOUTS.read_text())


def _rows():
    return _table()["layouts"]


def _expected(entry, which, first, second, block):
    """Rebuild one position from the vendored bit deltas."""
    slot, lane = entry[which]["base"]
    for dim, value in enumerate((block, first, second)):
        for bit, (dslot, dlane) in enumerate(entry[which]["bits"][dim]):
            if value >> bit & 1:
                slot += dslot
                lane += dlane
    return slot, lane


