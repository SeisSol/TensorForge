# the table against the tool
# --------------------------------------------------------------------------- #

def test_the_table_covers_exactly_what_the_calculator_knows():
    """Equality, so a newly covered instruction cannot arrive unnoticed.

    The calculator reaches CDNA 1--3 and RDNA 3--4. gfx950 and gfx125x are
    outside it, which is why it cannot be the only source of these facts and
    why the generated table records the gap rather than leaving those
    instructions silently absent.
    """
    assert set(layouts.FRAGMENT_BITS) == set(_rows())

    uncovered = {b for names in _table()["not_covered"].values() for b in names}
    catalogued = {op.builtin for op in catalog.MATRIX_OPS}
    assert uncovered == catalogued - set(layouts.FRAGMENT_BITS)
    assert uncovered, "the calculator does not reach every catalogue entry"


@pytest.mark.parametrize("op", [o for o in catalog.MATRIX_OPS
                                if layouts.covers(o)],
                         ids=lambda op: op.builtin)
def test_every_element_lands_where_the_calculator_puts_it(op):
    """Every element of every operand, not a sample.

    A layout is small enough to check exhaustively -- the largest here is a
    32x32 accumulator over two blocks -- and sampling would miss exactly the
    irregular bit that makes the table necessary.
    """
    entry = _rows()[op.builtin]
    extents = {"A": (op.m, op.k), "B": (op.k, op.n), "D": (op.m, op.n)}
    for which, (e1, e2) in extents.items():
        for block in range(op.blocks):
            for first in range(e1):
                for second in range(e2):
                    got = layouts.position(op, which, first, second, block)
                    assert got == _expected(entry, which, first, second, block), (
                        f"{op.builtin} {which}[{first}][{second}] block {block}")


@pytest.mark.parametrize("op", [o for o in catalog.MATRIX_OPS
                                if layouts.covers(o)],
                         ids=lambda op: op.builtin)
def test_a_fragment_fills_its_registers_exactly(op):
    """Every (slot, lane) an operand owns holds exactly one element.

    The property the per-lane widths in `catalog` assert and never check:
    `per_lane * wave` slots, `m * k * blocks` elements, and a replication
    factor relating them. Here it is checked against positions rather than
    counts, which is what catches a table that is self-consistent and
    misplaced.
    """
    extents = {"A": (op.a, op.m, op.k), "B": (op.b, op.k, op.n),
               "D": (op.d, op.m, op.n)}
    for which, (frag, e1, e2) in extents.items():
        seen = {}
        for block in range(op.blocks):
            for first in range(e1):
                for second in range(e2):
                    slot, lane = layouts.position(op, which, first, second, block)
                    assert 0 <= slot < frag.per_lane, f"{op.builtin} {which} slot"
                    assert 0 <= lane < op.wave, f"{op.builtin} {which} lane"
                    seen.setdefault((slot, lane), []).append((block, first, second))
        rep = op.replication(which.lower())
        assert len(seen) * rep == frag.per_lane * op.wave, (
            f"{op.builtin} {which}: {len(seen)} distinct positions for "
            f"{frag.per_lane * op.wave} slots at replication {rep}")
        assert all(len(v) == 1 for v in seen.values()), (
            f"{op.builtin} {which}: two elements share a position")


@pytest.mark.parametrize("op", [o for o in catalog.MATRIX_OPS
                                if layouts.covers(o)],
                         ids=lambda op: op.builtin)
def test_replication_agrees_between_llvm_and_amd(op):
    """Two sources, one number, nothing forcing them to agree.

    `MatrixOp.replication` divides LLVM's operand width by the shape. The
    calculator instead reports how many (slot, lane) pairs hold each element.
    They agree on all 32 covered instructions, including the RDNA 3 fragments
    where the answer is 2 at wave32 and 4 at wave64 -- which is the case that
    would expose a mistake in either.
    """
    entry = _rows()[op.builtin]
    for which in ("A", "B", "D"):
        assert entry[which]["replication"] == op.replication(which.lower()), (
            f"{op.builtin} {which}")


