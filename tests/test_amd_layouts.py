def test_the_tempting_rule_is_wrong_and_stays_written_down():
    """`slot = k % per_lane`, `lane = i + M*blocks*(k // per_lane)`.

    True for every CDNA entry, false on RDNA 4, which puts bit 2 of `k` in the
    lane and bits 0, 1 and 3 in the slot. Asserted so that the table cannot be
    replaced by the rule during a later tidy-up: a refactor that "simplifies"
    these rows would pass every other test in this file.
    """
    def by_rule(op, i, k):
        return (k % op.a.per_lane,
                i + op.m * op.blocks * (k // op.a.per_lane))

    agree, disagree = set(), set()
    for op in MEASURED:
        ok = all(layouts.position(op, "A", i, k) == by_rule(op, i, k)
                 for i in range(op.m) for k in range(op.k))
        (agree if ok else disagree).add(op.builtin)

    assert disagree, "the rule now reproduces every A layout; simplify the table"
    assert all("gfx12" in b for b in disagree), (
        f"the rule fails outside RDNA 4 as well: {sorted(disagree)}")


def test_the_fp64_accumulator_is_not_the_f32_one():
    """Same shape, same block count, opposite split of `i`.

    `mfma_f32_16x16x4f32` and `mfma_f64_16x16x4f64` are both 16x16x4 with one
    block and four accumulator elements per lane. The F32 one puts the low two
    bits of `i` in the slot and the high two in the lane; the F64 one does the
    reverse. This is the single clearest reason these layouts are tabulated
    and not derived.
    """
    f32 = next(o for o in catalog.MATRIX_OPS
               if o.builtin == "mfma_f32_16x16x4f32")
    f64 = next(o for o in catalog.MATRIX_OPS
               if o.builtin == "mfma_f64_16x16x4f64")
    assert (f32.m, f32.n, f32.k, f32.blocks) == (f64.m, f64.n, f64.k, f64.blocks)
    assert f32.d.per_lane == f64.d.per_lane

    assert layouts.position(f32, "D", 1, 0) == (1, 0)
    assert layouts.position(f64, "D", 1, 0) == (0, 16)


def test_the_fp64_operands_put_the_contraction_in_the_lanes():
    """Why `lane_batched` refuses them, read off the layout.

    `catalog` derives that from the shape: `k > 1` with one element per lane
    means part of the lane index carries the contraction. Here it is the
    positions saying the same thing -- B's `k` contributes 16 and 32 to the
    lane and nothing to the slot, so the top two lane bits are the
    contraction, and the generator's data operand has the leading dimension
    there.
    """
    for name in ("mfma_f64_4x4x4f64", "mfma_f64_16x16x4f64"):
        op = next(o for o in catalog.MATRIX_OPS if o.builtin == name)
        assert not op.lane_batched()
        lanes = {layouts.position(op, "B", k, 0)[1] for k in range(op.k)}
        slots = {layouts.position(op, "B", k, 0)[0] for k in range(op.k)}
        assert lanes == {0, 16, 32, 48}, f"{name}: k moves the lane"
        assert slots == {0}, f"{name}: k does not move the slot"


def test_the_k1_f32_tiles_keep_the_contraction_out_of_the_lanes():
    """The other half of the same statement, for the tiles in use today."""
    for tile in catalog.MFMA_TILES:
        op = tile.op
        if not layouts.covers(op):
            continue
        assert op.k == 1
        assert layouts.position(op, "B", 0, 0) == (0, 0)
        lanes = {layouts.position(op, "B", 0, n)[1] for n in range(op.n)}
        assert lanes == set(range(op.n)), (
            f"{op.builtin}: N is the low lane bits, so blocks can carry the rest")


