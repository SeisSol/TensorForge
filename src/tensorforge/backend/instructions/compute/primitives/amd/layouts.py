def _place(bits: Tuple[int, ...], value: int) -> Tuple[int, int]:
    slot = lane = 0
    for bit, weight in enumerate(bits):
        if value >> bit & 1:
            if weight < 0:
                slot -= weight
            else:
                lane += weight
    return slot, lane


def position(op, which: str, first: int, second: int,
             block: int = 0) -> Optional[Tuple[int, int]]:
    """`(slot, lane)` holding one element, or `None` if untabulated.

    `first` and `second` are the operand's own indices --- `A[m][k]`,
    `B[k][n]`, `D[m][n]` --- not the generator's.  Which of them is the
    contraction is the caller's business and differs between A and B, which is
    exactly the confusion a single "row, column" naming would invite.

    Where the operand is replicated, this is the lowest lane holding the
    element.  `MatrixOp.replication` says how many hold it; the RDNA 3
    fragments are the ones where that is not 1.
    """
    row = FRAGMENT_BITS.get(op.builtin)
    if row is None:
        return None
    blk, one, two = row[{'A': 0, 'B': 3, 'D': 6}[which.upper()]:][:3]
    slot, lane = _place(blk, block)
    for bits, value in ((one, first), (two, second)):
        s, l = _place(bits, value)
        slot += s
        lane += l
    return slot, lane


def covers(op) -> bool:
    """Is this instruction's fragment layout established?"""
    return op.builtin in FRAGMENT_BITS
