"""Where each element of a matrix operand lives.

`catalog` says how *many* elements of an operand a lane holds.  This says
*which*, which is the part an emitter needs: the fragment layout is the
difference between a correct kernel and one that reads the wrong lanes out of
correctly typed registers, and nothing in the type system catches that.

It is a table, not an algebra --- the same shape and the same reason as
`relayout`.  There is a tempting rule: `A[i][k]` at ``lane = i + M*block +
M*blocks*(k // per_lane)``, ``slot = k % per_lane``.  It reproduces every CDNA
entry and it is wrong on RDNA 4, which puts bit 2 of `k` in the lane and bits
0, 1 and 3 in the slot.  `D` has no rule at all: `mfma_f32_16x16x4f32` puts
the low two bits of `i` in the slot and the high two in the lane, and
`mfma_f64_16x16x4f64`, at the same shape and the same block count, does the
opposite.

Every layout is *linear in the index bits*, which is what makes the table
short: one destination per bit of each index, rather than one row per element.
A positive entry is a lane weight, a negative one a slot weight.  So::

    'mfma_f64_16x16x4f64': (
        (),        (1, 2, 4, 8),     (16, 32),        # A[i][k]
        ...

reads as: A has no block dimension, `i` contributes ``1*bit0 + 2*bit1 +
4*bit2 + 8*bit3`` to the lane, and `k` contributes ``16*bit0 + 32*bit1``.

The rows come from AMD's matrix instruction calculator
(https://github.com/ROCm/amd_matrix_instruction_calculator, MIT), which is the
published form of these layouts.  `tools/amd_matrix_layouts.py` drives it and
vendors the result in `tests/data/amd_matrix_layouts.json`;
`tests/test_amd_layouts.py` fails if a row here disagrees.  The tool is a
regeneration input, not a dependency: it is an argparse script rather than a
library, it covers CDNA 1--3 and RDNA 3--4 and not gfx950 or gfx125x, and code
generation must not need it to run.

An instruction it does not cover has no row, and therefore no fragment.  That
is the intended outcome: no row means an emitter cannot place the operand and
declines, rather than placing it on a guess.
"""

