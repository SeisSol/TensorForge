PREAMBLE = r'''\usepackage{amsmath}
\usepackage{array}
\usepackage{booktabs}
\usepackage{pgfplots}
'''


def standalone(figure: str, style_path: str = 'tfstyle',
               width: str = '8.6cm') -> str:
    """A document that is the one figure, for `\\includegraphics` where the
    paper does not `\\input` pgfplots itself.  8.6 cm is a two-column
    paper's column."""
    return (r'\documentclass{standalone}' + '\n' + PREAMBLE
            + f'\\newlength{{\\tfwidth}}\\setlength{{\\tfwidth}}{{{width}}}\n'
            + f'\\input{{{style_path}}}\n'
            + '\\begin{document}\n'
            + f'\\input{{{figure}}}\n'
            + '\\end{document}\n')


def compile_tex(path: Path, timeout: float = 600.0) -> Tuple[bool, str]:
    """`pdflatex` on one file, in its directory; `(ok, why not)`."""
    tex = shutil.which('pdflatex')
    if tex is None:
        return False, 'pdflatex not found'
    try:
        proc = subprocess.run(
            [tex, '-interaction=nonstopmode', '-halt-on-error', path.name],
            cwd=path.parent, capture_output=True, text=True,
            timeout=timeout, check=False)
    except subprocess.TimeoutExpired:
        return False, f'pdflatex timed out after {timeout:.0f}s'
    if proc.returncode != 0:
        errors = [ln for ln in proc.stdout.splitlines() if ln.startswith('!')]
        return False, (errors[0] if errors else f'exit {proc.returncode}') \
            + f' (see {path.with_suffix(".log")})'
    return True, ''
