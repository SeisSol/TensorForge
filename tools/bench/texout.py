#: A row of `table` that is a little space rather than a rule.
GAP = ('addlinespace',)


def table(columns: str, headers: Sequence,
          rows: Sequence[Optional[Sequence[str]]], comment: str = '') -> str:
    """A booktabs `tabular`.  `headers` is one or more header rows, already
    LaTeX -- a string among them is set as it stands, which is how a
    `\\cmidrule` gets between two.  In `rows`, `None` is a `\\midrule`,
    between the groups of a table, and `GAP` a little space, between the
    rows of one kernel and the next inside a group."""
    head = ''.join(f'% {line}\n' for line in comment.splitlines())
    lines = [f'\\begin{{tabular}}{{{columns}}}', '\\toprule']
    for h in headers:
        lines.append(h if isinstance(h, str) else ' & '.join(h) + r' \\')
    lines.append('\\midrule')
    for r in rows:
        if r is None:
            lines.append('\\midrule')
        elif r is GAP:
            lines.append('\\addlinespace')
        else:
            lines.append(' & '.join(r) + r' \\')
    lines += ['\\bottomrule', '\\end{tabular}']
    return head + '\n'.join(lines) + '\n'


def stack(lines: Iterable[str]) -> str:
    """Several lines in one cell, top-aligned."""
    lines = list(lines)
    if len(lines) == 1:
        return lines[0]
    return (r'\begin{tabular}[t]{@{}l@{}}' + r' \\ '.join(lines)
            + r'\end{tabular}')


