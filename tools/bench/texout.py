@dataclass
class Plot:
    """One `\\addplot`: a style, the points, and what the legend calls it.
    A `None` coordinate breaks the line, as in the SVG charts: a gap is
    left open rather than drawn across.  `labels`, where given, is set
    beside each point -- sparingly: the order a point was run at, not its
    value."""
    style: str
    points: Sequence[Tuple[Optional[float], Optional[float]]]
    legend: Optional[str] = None
    labels: Sequence[str] = ()
    label_anchor: str = 'south west'

    def render(self) -> str:
        labelled = bool(self.labels)
        rows = ['x y m' if labelled else 'x y']
        for i, (x, y) in enumerate(self.points):
            label = (self.labels[i] if i < len(self.labels) else '')
            if x is None or y is None:
                rows.append('nan nan {}' if labelled else 'nan nan')
                continue
            rows.append(f'{coordinate(x)} {coordinate(y)}'
                        + (f' {{{label}}}' if labelled else ''))
        options = [self.style]
        if labelled:
            options += ['nodes near coords', 'point meta=explicit symbolic',
                        'every node near coord/.append style='
                        f'{{tf label, anchor={self.label_anchor}}}']
        table_opts = ['row sep=\\\\', 'x=x', 'y=y',
                      'unbounded coords=jump']
        if labelled:
            table_opts.append('meta=m')
        body = ''.join(f'    {r} \\\\\n' for r in rows)
        legend = (f'\\addlegendentry{{{self.legend}}}\n'
                  if self.legend is not None else '')
        # Not `\\addplot+`: the cycle list would add its own colour and
        # dash to a style that already says what the series is.
        return (f'\\addplot[{", ".join(options)}]\n'
                f'  table[{", ".join(table_opts)}] {{\n{body}  }};\n'
                + legend)


@dataclass
class Axis:
    """One pgfplots axis: its options, its plots, and anything drawn in it
    verbatim (a roof, a rule, a label)."""
    options: List[str] = field(default_factory=list)
    plots: List[Plot] = field(default_factory=list)
    raw: List[str] = field(default_factory=list)
    kind: str = 'axis'

    def render(self, inside_group: bool = False) -> str:
        opts = ',\n  '.join(self.options)
        body = ''.join(p.render() for p in self.plots) + ''.join(self.raw)
        if inside_group:
            return f'\\nextgroupplot[\n  {opts}]\n{body}'
        return (f'\\begin{{{self.kind}}}[\n  {opts}]\n{body}'
                f'\\end{{{self.kind}}}\n')


def picture(axes: Sequence[Axis], group: Optional[str] = None,
            comment: str = '', options: Sequence[str] = ()) -> str:
    """A `tikzpicture` of one axis, or of a group of them laid out by
    `group` (the `group style` value, e.g. `group size=1 by 3`), with
    `options` for every axis of the group."""
    head = ''.join(f'% {line}\n' for line in comment.splitlines())
    if group is None:
        if len(axes) != 1:
            raise ValueError('several axes need a group layout')
        return (head + '\\begin{tikzpicture}\n' + axes[0].render()
                + '\\end{tikzpicture}\n')
    body = ''.join(a.render(inside_group=True) for a in axes)
    opts = ', '.join(['tf', f'group style={{{group}}}', *options])
    return (head + '\\begin{tikzpicture}\n'
            f'\\begin{{groupplot}}[{opts}]\n'
            + body + '\\end{groupplot}\n\\end{tikzpicture}\n')


def hrule(y: float, label: str = '', anchor: str = 'south east',
          pos: Optional[float] = None) -> str:
    """A horizontal rule across the whole axis at `y`, whatever the x axis
    is -- logarithmic, symbolic or plain -- with an optional label at its
    right end, or at `pos` along it (0 the left end, 1 the right).  Drawn,
    not plotted, so it widens no axis limit."""
    where = f'pos={pos:.2f}, ' if pos is not None else ''
    node = (f' node[{where}anchor={anchor}, tf label] {{{label}}}'
            if label else '')
    return (f'\\draw[tf rule] ({{rel axis cs:0,0}}|-{{axis cs:1,{y:.6g}}}) '
            f'-- ({{rel axis cs:1,0}}|-{{axis cs:1,{y:.6g}}}){node};\n')


