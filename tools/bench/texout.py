_SPECIAL = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$',
            '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}',
            '~': r'\textasciitilde{}', '^': r'\textasciicircum{}',
            '—': '---', '–': '--', '÷': r'$\div$', '×': r'$\times$'}


def escape(text: str) -> str:
    """Text-mode LaTeX for a name that came from data."""
    return ''.join(_SPECIAL.get(c, c) for c in str(text))


def num(value: Optional[float], digits: int = 3, unit: str = '') -> str:
    """A number as a table cell: significant digits, thin spaces between
    thousands, a dash where there is none."""
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return '--'
    a = abs(value)
    if a >= 1000:
        text = f'{value:,.0f}'.replace(',', r'\,')
    elif a == 0:
        text = '0'
    else:
        decimals = max(0, digits - 1 - int(math.floor(math.log10(a))))
        text = f'{value:.{decimals}f}'
    return text + (f'\\,{unit}' if unit else '')


def coordinate(value: float) -> str:
    """A coordinate pgfplots reads exactly and briefly."""
    return f'{value:.6g}'


