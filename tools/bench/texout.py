"""The figures and tables as LaTeX: pgfplots and booktabs, written as text.

`pdfout.py` is the second rendering of the exploration charts, for sending.
This is the third, for typesetting: a figure that goes into a paper has to
be set in the paper's own fonts and at its column width, and a PDF drawn
here in Helvetica at 760 pixels comes out at a third of a point per pixel
in a 3.5-inch column -- unreadable -- with fonts some publishers' checkers
reject for not being embedded.  pgfplots draws in the document's fonts at
whatever width the document says, and LaTeX embeds them.

Written by hand for the reason the other two are: nothing here needs more
than string formatting, and the machine this runs on needs no TeX at all.
The document that `\\input`s the output does.

## What the output asks of the document

`pgfplots` (with the `groupplots` library, which `STYLE` loads) and, for
the tables, `booktabs` and `array`.  Every figure is a bare `tikzpicture`
sized by the lengths `\\tfwidth` and `\\tfheight`, which `STYLE` makes the
line's width unless the document defined them first -- so a paper sets the
width once, and a figure needs no edit to move from one column to two.

## Colour

Identity is a categorical palette in a fixed order, validated for colour
vision deficiency on adjacent pairs (`dataviz`'s reference set: worst
adjacent CVD Delta E 9.1); past three series the pairs a scatter puts side
by side are not all safe, so every series also carries its own mark, and
the order a kernel was run at is a number beside its point rather than a
colour.  An ordered quantity -- the discretisation order in a bar group --
is one hue from light to dark instead, which reads as more and less.
"""

from __future__ import annotations

import math
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable, List, Optional, Sequence, Tuple

#: Identity: kernels, machines.  Fixed order, never cycled -- a ninth
#: series gets a mark of its own on a repeated colour.
CATEGORICAL = ('2A78D6', 'EB6834', '1BAF7A', 'EDA100', 'E87BA4', '008300',
               '6250D6', 'E34948')

#: The second channel, so that identity never rests on colour alone.
MARKS = ('*', 'square*', 'triangle*', 'diamond*', 'pentagon*', 'o',
         'square', 'triangle')

#: Ordered values, light to dark: one hue, each step distinguishable and
#: the lightest still clear of the page (2:1).
ORDINAL = ('86B6EF', '6DA7EC', '5598E7', '3987E5', '2A78D6', '256ABF',
           '1C5CAB', '184F95', '104281')

#: Ink, by role: what a number or a label is set in, never a series colour.
INK = {'tfink': '0B0B0B', 'tfsecondary': '52514E', 'tfmuted': '898781',
       'tfgrid': 'E1E0D9', 'tfaxis': 'C3C2B7'}


def ordinal(n: int) -> List[int]:
    """Which `ORDINAL` steps `n` ordered values take: spread over the ramp,
    so that three orders are not three neighbouring blues."""
    if n <= 1:
        return [4]
    span = len(ORDINAL) - 1
    return [round(i * span / (n - 1)) for i in range(n)]


STYLE = r'''%% generated by tools/bench/texout.py -- the styles every figure
%% uses.  \tfwidth and \tfheight are lengths: set them before \input-ing
%% this to size every figure at once; they default to the line width.
\usepgfplotslibrary{groupplots}
\pgfplotsset{compat=1.16}
%(colors)s
\ifdefined\tfwidth\else\newlength{\tfwidth}\setlength{\tfwidth}{\linewidth}\fi
\ifdefined\tfheight\else\newlength{\tfheight}\setlength{\tfheight}{0.62\tfwidth}\fi
\pgfplotsset{
  tf/.style={
    width=\tfwidth, height=\tfheight,
    font=\footnotesize,
    tick label style={font=\scriptsize, color=tfsecondary},
    label style={font=\footnotesize, color=tfink},
    title style={font=\footnotesize, color=tfink},
    legend style={font=\scriptsize, draw=none, fill=none,
                  text=tfink, cells={anchor=west}},
    legend cell align=left,
    axis line style={tfaxis}, tick style={tfaxis},
    grid=major, major grid style={tfgrid, line width=0.3pt},
    every axis plot/.append style={line width=0.8pt},
    clip marker paths=true,
    scaled ticks=false,
    /pgf/number format/1000 sep={\,},
  },
  tf legend above/.style={
    legend style={at={(0.5,1.02)}, anchor=south, legend columns=3,
                  /tikz/every even column/.append style={column sep=0.6em}},
  },
%(series)s
}
%% Drawing styles, in TikZ's namespace so that a \draw or a \node in an axis
%% finds them as well as an \addplot does.
\tikzset{
  tf roof/.style={tfink, line width=1pt, mark=none},
  tf unit/.style={tfmuted, densely dashed, line width=0.7pt, mark=none},
  tf rule/.style={tfmuted, line width=0.6pt, mark=none},
  tf label/.style={font=\scriptsize, text=tfsecondary, inner sep=1pt},
}
'''


def style() -> str:
    colors = '\n'.join(
        [f'\\definecolor{{tfc{i + 1}}}{{HTML}}{{{c}}}'
         for i, c in enumerate(CATEGORICAL)]
        + [f'\\definecolor{{tfo{i + 1}}}{{HTML}}{{{c}}}'
           for i, c in enumerate(ORDINAL)]
        + [f'\\definecolor{{{k}}}{{HTML}}{{{v}}}' for k, v in INK.items()])
    series = '\n'.join(
        f'  tf s{i + 1}/.style={{color=tfc{(i % len(CATEGORICAL)) + 1}, '
        f'mark={MARKS[i % len(MARKS)]}, mark size=1.6pt, '
        f'mark options={{solid}}}},'
        for i in range(2 * len(CATEGORICAL)))
    return STYLE % {'colors': colors, 'series': series}


